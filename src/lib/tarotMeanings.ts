export function getCardMeaning(cardId: number, isReversed: boolean = false): string {
  if (isReversed) {
    return tarotReversedMeanings[cardId] || "معنی معکوس این کارت به زودی اضافه خواهد شد.";
  }
  return tarotMeanings[cardId] || "معنی این کارت به زودی اضافه خواهد شد.";
}

export function getDailyInterpretation(card: any, isReversed: boolean = false): string {
  const meaning = getCardMeaning(card.id, isReversed);
  const name = card.nameFa;
  if (isReversed) {
    return `امروز کارت «${name}» به صورت معکوس برای شما ظاهر شده است. این کارت هشدار می‌دهد که انرژی‌های آن در درون شما مسدود شده یا نیاز به بازنگری دارند. پیام آن برای امروز: ${meaning}. سعی کنید با دقت بیشتری به احساسات و اعمال خود نگاه کنید.`;
  }

  if (card.isMajor) {
    return `امروز انرژی قدرتمند کارت «${name}» بر زندگی شما سایه افکنده است. این کارت نشان می‌دهد که ${meaning}. امروز یک روز مهم برای خودشناسی و پذیرش تحولات بزرگ است. به ندای درون خود گوش دهید.`;
  }

  switch (card.suit) {
    case "cups":
      return `امروز کارت «${name}» از دسته جام‌ها پیام‌آور احساسات و شهود است. پیام آن برای امروز شما این است که ${meaning}. به روابط، قلب و احساسات درونی خود توجه بیشتری نشان دهید.`;
    case "swords":
      return `امروز کارت «${name}» از دسته شمشیرها انرژی ذهن و منطق را به همراه دارد. این کارت به شما می‌گوید که ${meaning}. از قدرت تفکر و کلام خود برای حل چالش‌ها استفاده کنید.`;
    case "wands":
      return `امروز کارت «${name}» از دسته چوب‌ها، آتش اشتیاق و اقدام را در شما روشن می‌کند. پیام آن برای امروز این است که ${meaning}. زمان آن رسیده که از منطقه امن خود خارج شوید.`;
    case "pentacles":
      return `امروز کارت «${name}» از دسته سکه‌ها بر جنبه‌های مادی و عملی زندگی تأکید دارد. پیام آن برای امروز شما این است که ${meaning}. به کار و امور مالی خود توجه ویژه‌ای داشته باشید.`;
    default:
      return `امروز کارت «${name}» برای شما ظاهر شده است. پیام کلیدی آن برای امروز شما: ${meaning}.`;
  }
}